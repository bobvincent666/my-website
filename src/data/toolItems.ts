export function getToolById(id: string | null | undefined) {
  if (!id) {
    return undefined;
  }

  return toolItems.find((item) => item.id === id);
}

export function getToolsByCategory(categoryId: string) {
  return toolItems.filter((item) => item.categoryId === categoryId);
}
